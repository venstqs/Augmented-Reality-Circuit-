"""
Export the trained model to TensorFlow.js and wire it into the Expo app.

Usage:
    # Option A: From a downloaded folder/zip of model.json + .bin shards (e.g. from Colab)
    python export_tfjs.py --dir path/to/exported_folder

    # Option B: Directly from trained PyTorch weights (if tensorflowjs converter is available)
    python export_tfjs.py --weights runs/circuit/weights/best.pt
"""
import argparse
import json
import shutil
import zipfile
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
DEFAULT_CLASSES = ["battery", "resistor", "bulb", "led", "switch", "text"]


def register_assets(src_dir: Path, imgsz: int, labels: list):
    dst = APP / "assets" / "model"
    if dst.exists():
        shutil.rmtree(dst)
    dst.mkdir(parents=True)

    for f in src_dir.iterdir():
        if f.suffix in (".json", ".bin"):
            shutil.copy2(f, dst / f.name)

    (dst / "labels.json").write_text(json.dumps(labels))

    manifest_path = dst / "model.json"
    if not manifest_path.exists():
        raise SystemExit(f"Error: model.json not found in {src_dir}")

    manifest = json.loads(manifest_path.read_text())
    shards = [p for group in manifest["weightsManifest"] for p in group["paths"]]
    reqs = ",\n    ".join(f"require('../../assets/model/{s}')" for s in shards)

    (APP / "src" / "ml" / "modelRegistry.js").write_text(
        "/** AUTO-GENERATED by training/export_tfjs.py - do not edit by hand. */\n"
        "export const MODEL = {\n"
        "  json: require('../../assets/model/model.json'),\n"
        f"  weights: [\n    {reqs},\n  ],\n"
        "  labels: require('../../assets/model/labels.json'),\n"
        f"  imgsz: {imgsz},\n"
        "};\n"
    )
    print(f"\n[OK] Copied {len(shards)} weight shard(s) + labels {labels} into the app.")
    print("[OK] Updated src/ml/modelRegistry.js with Metro bundler require() paths.")
    print("\nDone! Start your app with:  npx expo start -c")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", help="Path to folder or .zip containing exported model.json and .bin shards")
    ap.add_argument("--weights", default="runs/circuit/weights/best.pt")
    ap.add_argument("--imgsz", type=int, default=320)
    args = ap.parse_args()

    if args.dir:
        p = Path(args.dir)
        if p.suffix == ".zip":
            extract_dir = p.parent / p.stem
            with zipfile.ZipFile(p, "r") as z:
                z.extractall(extract_dir)
            p = extract_dir
        # If nested inside a subfolder, locate model.json
        model_file = next(p.rglob("model.json"), None)
        if not model_file:
            raise SystemExit(f"Could not find model.json inside {p}")
        labels = DEFAULT_CLASSES
        labels_file = next(p.rglob("labels.json"), None)
        if labels_file:
            labels = json.loads(labels_file.read_text())
        register_assets(model_file.parent, args.imgsz, labels)
        return

    # Direct export using ultralytics
    from ultralytics import YOLO

    model = YOLO(args.weights)
    names = model.names
    labels = [names[i] for i in sorted(names)]
    exported = Path(model.export(format="tfjs", imgsz=args.imgsz, half=False, int8=False))
    register_assets(exported, args.imgsz, labels)


if __name__ == "__main__":
    main()
