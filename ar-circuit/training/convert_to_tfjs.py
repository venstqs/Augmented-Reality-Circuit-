"""
Converts runs/circuit_full/weights/best_saved_model to TensorFlow.js format
and registers it directly in the React Native Expo app.
"""
import sys
import unittest.mock

# 1. Patch protobuf runtime version check so TensorFlow imports cleanly
import google.protobuf.runtime_version
google.protobuf.runtime_version.ValidateProtobufRuntimeVersion = lambda *args, **kwargs: None

# 2. Mock Linux-only tensorflow_decision_forests so tensorflowjs works on Windows
sys.modules['tensorflow_decision_forests'] = unittest.mock.MagicMock()

from pathlib import Path
import json
import shutil
import tensorflowjs as tfjs

APP_DIR = Path(__file__).resolve().parent.parent
SAVED_MODEL_DIR = Path(__file__).resolve().parent / "runs" / "circuit_full" / "weights" / "best_saved_model"
OUT_DIR = APP_DIR / "assets" / "model"

DEFAULT_CLASSES = ["battery", "resistor", "bulb", "led", "switch", "text"]

def main():
    print(f"Loading SavedModel from: {SAVED_MODEL_DIR}")
    if not SAVED_MODEL_DIR.exists():
        raise SystemExit(f"SavedModel not found at {SAVED_MODEL_DIR}")

    if OUT_DIR.exists():
        shutil.rmtree(OUT_DIR)
    OUT_DIR.mkdir(parents=True)

    print("Converting SavedModel to TensorFlow.js web model...")
    tfjs.converters.convert_tf_saved_model(
        str(SAVED_MODEL_DIR),
        str(OUT_DIR),
        signature_def="serving_default",
        saved_model_tags="serve",
    )

    # Write labels.json
    (OUT_DIR / "labels.json").write_text(json.dumps(DEFAULT_CLASSES, indent=2))
    print(f"[OK] Generated labels.json with classes: {DEFAULT_CLASSES}")

    # Inspect manifest
    manifest_path = OUT_DIR / "model.json"
    if not manifest_path.exists():
        raise SystemExit(f"Error: model.json not found in {OUT_DIR}")

    manifest = json.loads(manifest_path.read_text())
    shards = [p for group in manifest["weightsManifest"] for p in group["paths"]]
    print(f"[OK] Found {len(shards)} weight shard(s): {shards}")

    reqs = ",\n    ".join(f"require('../../assets/model/{s}')" for s in shards)

    # Update modelRegistry.js
    registry_file = APP_DIR / "src" / "ml" / "modelRegistry.js"
    registry_content = (
        "/** AUTO-GENERATED by training/convert_to_tfjs.py - do not edit by hand. */\n"
        "export const MODEL = {\n"
        "  json: require('../../assets/model/model.json'),\n"
        f"  weights: [\n    {reqs},\n  ],\n"
        "  labels: require('../../assets/model/labels.json'),\n"
        "  imgsz: 320,\n"
        "};\n"
    )
    registry_file.write_text(registry_content)
    print(f"[OK] Updated {registry_file} with Metro bundler require paths!")
    print("\n[SUCCESS] The trained YOLOv8 circuit model is now fully bundled into your Expo app!")

if __name__ == "__main__":
    main()
